	  uint8_t BH1750_CONT_HIGH_RES = 0x10;      // continu high-res mode
	  uint8_t cmd = BH1750_CONT_HIGH_RES;

	  // Commando sturen naar BH1750
	  HAL_I2C_Master_Transmit(&hi2c1, BH1750_ADDR, &cmd, 1, HAL_MAX_DELAY);
	  HAL_Delay(120); // meettijd volgens datasheet
